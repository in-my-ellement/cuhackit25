function formatPoints(points) {
    return points.map(point => `{ x: ${point.x}, y: ${point.y} }`).join(',');
}

function standardizeShapes(shapes) {
    // Create a deep copy of shapes and standardize each shape individually
    const standardizedShapes = shapes.map(shape => {
      // Extract all x and y values for this shape only
      const xValues = shape.points.map(point => point.x);
      const yValues = shape.points.map(point => point.y);
  
      // Calculate mean for x and y of this shape
      const meanX = xValues.reduce((sum, val) => sum + val, 0) / xValues.length;
      const meanY = yValues.reduce((sum, val) => sum + val, 0) / yValues.length;
  
      // Calculate standard deviation for x and y of this shape
      const varX = xValues.reduce((sum, val) => sum + Math.pow(val - meanX, 2), 0) / xValues.length;
      const varY = yValues.reduce((sum, val) => sum + Math.pow(val - meanY, 2), 0) / yValues.length;
  
      const stdDevX = Math.sqrt(varX);
      const stdDevY = Math.sqrt(varY);
  
      // Standardize each point in this shape
      const standardizedPoints = shape.points.map(point => ({
        x: (point.x - meanX) / stdDevX,
        y: (point.y - meanY) / stdDevY
      }));
  
      return {
        points: standardizedPoints,
        name: shape.name
      };
    });
  
    return standardizedShapes;
  }

